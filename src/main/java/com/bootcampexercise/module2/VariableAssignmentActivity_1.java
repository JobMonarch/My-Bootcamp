package com.bootcampexercise.module2;

public class VariableAssignmentActivity_1 {
    public static void main(String[] args) {
        int number = 0; // our starting value

        System.out.println("Before Update: "+ number); //prints the value before the update

        number = 25; // updating the value

        System.out.println("After Update: " + number); // prints the value
    }
}